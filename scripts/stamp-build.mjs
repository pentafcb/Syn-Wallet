// Build stamp: generates ONE build id per `npm run build` and writes it
// into both the client tree and the server tree, so the shipped client
// bundle and the shipped server always agree on the id of the build they
// belong to. The client compares its baked-in id against the one the
// server reports on /api/health; a mismatch means a newer build is being
// served and the open copy is stale (see the update pill in main.ts).
// The id is a UTC timestamp plus the git short hash when available —
// uniqueness comes from the timestamp, the hash is only a debugging aid.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
let git = '';
try {
  git = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
} catch { /* source tarballs deployed to the box may not carry .git */ }
const ts = new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z');
const id = git ? `${ts}-${git}` : ts;
const body = `// GENERATED by scripts/stamp-build.mjs during \`npm run build\` — do not edit by hand.
// Identical in the client bundle and the server so the client can detect,
// via /api/health, that the server is running a newer build than the copy
// it was loaded from.
export const BUILD_ID = '${id}';
`;
fs.writeFileSync(path.join(root, 'client', 'build-id.ts'), body);
fs.writeFileSync(path.join(root, 'src', 'build-id.ts'), body);
console.log(`[stamp] build id ${id}`);
